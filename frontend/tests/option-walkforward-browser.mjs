import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const browser = await chromium.launch({ channel: process.env.ATS_BROWSER_CHANNEL || 'msedge', headless: true });
try {
  const page = await browser.newPage();
  page.setDefaultTimeout(180000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.argv[2]);
  await page.getByLabel('Username', { exact: true }).fill('owner');
  await page.getByLabel('Password', { exact: true }).fill(process.env.ATS_TEST_OWNER_PASSWORD);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Backtests', exact: true }).click();
  const controls = page.getByRole('region', { name: 'Walk-forward controls', exact: true });
  await controls.getByLabel('Walk-forward experiment', { exact: true }).selectOption('walktest01');
  await controls.getByLabel('Research reason', { exact: true }).fill('Synthetic option chronological browser fixture');
  await controls.getByLabel('Type RUN WALK FORWARD', { exact: true }).fill('RUN WALK FORWARD');
  await controls.getByRole('button', { name: 'Launch walk-forward research', exact: true }).click();
  await controls.getByText(/walktest01: COMPLETED.*REPORT PUBLISHED/).waitFor();
  await page.getByLabel('Historical run', { exact: true }).selectOption('walktest01');
  await page.getByText('Strategy: long-option-breakout / version 1', { exact: true }).waitFor();
  const adequacy = page.getByRole('region', { name: 'Historical window adequacy' });
  assert.match(await adequacy.innerText(), /test00001 \(OUT_OF_SAMPLE\)/);
  assert.match(await adequacy.innerText(), /59\.999999 elapsed seconds/);
  assert.match(await adequacy.innerText(), /BELOW_MINIMUM/);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export simulated report JSON', exact: true }).click();
  const download = await downloadEvent;
  const stream = await download.createReadStream();
  const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const report = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  assert.equal(report.simulated, true);
  assert.equal(report.catalog_integrity, 'AUDIT_BOUND');
  assert.equal(report.run.strategy_id, 'long-option-breakout');
  assert.equal(report.trades.length, 1);
  assert.equal(report.trades[0].quantity, 2);
  assert.equal(Number(report.trades[0].gross_pnl), -8);
  assert.ok(Number(report.trades[0].charges) > 0);
  assert.equal(Math.round(Number(report.trades[0].net_pnl) * 100), -800 - Math.round(Number(report.trades[0].charges) * 100));
  assert.equal(report.window_disclosure.windows.length, 1);
  assert.equal(report.window_disclosure.windows[0].minimum_calendar_days, 60);
  assert.equal(report.window_disclosure.windows[0].continuous_coverage_verified, false);
  await page.reload();
  await page.getByRole('button', { name: 'Backtests', exact: true }).click();
  await page.getByLabel('Historical run', { exact: true }).selectOption('walktest01');
  await page.getByText('Strategy: long-option-breakout / version 1', { exact: true }).waitFor();
  assert.match(await adequacy.innerText(), /BELOW_MINIMUM/);
  assert.deepEqual(errors, []);
  process.stdout.write('WALKFORWARD_VERIFIED\n');
} finally { await browser.close(); }
